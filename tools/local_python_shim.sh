#!/bin/sh
# Generate <plugin>/bin/python3 — a NARROW interpreter shim.
#
# Why this exists
# ---------------
# The skills invoke their helper scripts as `python3 scripts/....py`. On this
# machine `python3` resolves to the WorkBuddy-managed 3.13.12, whose
# site-packages is root-owned (read-only) and whose user-site is knocked out of
# sys.path by the harness's PYTHONPATH shim — so none of the runtime
# dependencies in requirements.txt can be installed where `python3` looks.
#
# CodeBuddy prepends a plugin's bin/ to PATH for Bash tool calls
# (process.env.PATH = [...pluginBinPaths, ...rest]), so a `python3` placed here
# wins. Shadowing python3 for the whole session would be reckless, so this shim
# is deliberately narrow: it reroutes ONLY `*scripts/*.py` invocations to the
# dependency-complete interpreter and passes everything else through to the
# real managed python3.
#
# The generated file is gitignored — it embeds machine-local paths and must not
# ship in a distributed plugin.
#
# Usage: sh tools/local_python_shim.sh [--venv PATH]

set -eu

PLUGIN_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
VENV_PY=${1:-}
if [ "$VENV_PY" = "--venv" ]; then
    VENV_PY=${2:-}
else
    VENV_PY=""
fi
[ -n "$VENV_PY" ] || VENV_PY="$HOME/.workbuddy-ai/binaries/python/envs/default/bin/python"

REAL_PY=$(command -v python3 || true)
if [ -z "$REAL_PY" ]; then
    echo "error: python3 not found on PATH" >&2
    exit 1
fi
if [ ! -x "$VENV_PY" ]; then
    echo "error: interpreter not executable: $VENV_PY" >&2
    echo "hint: create it with  python3 -m venv <dir> && <dir>/bin/pip install -r requirements.txt" >&2
    exit 1
fi

# A venv's bin/python is a symlink to the base interpreter, so file identity
# proves nothing — the environment is distinguished by sys.prefix (via
# pyvenv.cfg). Refuse only when the two resolve to the SAME environment.
VENV_PREFIX=$("$VENV_PY" -c 'import sys; print(sys.prefix)' 2>/dev/null || true)
REAL_PREFIX=$("$REAL_PY" -c 'import sys; print(sys.prefix)' 2>/dev/null || true)
if [ -n "$VENV_PREFIX" ] && [ "$VENV_PREFIX" = "$REAL_PREFIX" ]; then
    echo "error: $VENV_PY is not a separate environment (same sys.prefix as python3)" >&2
    echo "hint: point --venv at a real venv, not the base interpreter" >&2
    exit 1
fi

# Sanity-check that the venv actually carries the dependencies.
if ! "$VENV_PY" -c "import yaml, jsonschema" 2>/dev/null; then
    echo "error: $VENV_PY is missing runtime dependencies" >&2
    echo "hint: $VENV_PY -m pip install -r requirements.txt" >&2
    exit 1
fi

mkdir -p "$PLUGIN_ROOT/bin"
cat > "$PLUGIN_ROOT/bin/python3" <<EOF
#!/bin/sh
# GENERATED by tools/local_python_shim.sh — do not edit, do not commit.
# Routes ARS's own scripts to a dependency-complete interpreter; every other
# python3 invocation keeps using the managed interpreter unchanged.
VENV="$VENV_PY"
REAL="$REAL_PY"
case "\${1:-}" in
    *scripts/*.py)
        if [ -x "\$VENV" ]; then exec "\$VENV" "\$@"; fi
        ;;
esac
exec "\$REAL" "\$@"
EOF
chmod +x "$PLUGIN_ROOT/bin/python3"

echo "wrote $PLUGIN_ROOT/bin/python3"
echo "  ARS scripts -> $VENV_PY"
echo "  everything else -> $REAL_PY"
